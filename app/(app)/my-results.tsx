import React, { useCallback, useEffect, useState } from 'react';
import { ActivityIndicator, Alert, Linking, Pressable, RefreshControl, SafeAreaView, ScrollView, StyleSheet, Text, View } from 'react-native';
import { router } from 'expo-router';

import { useAuth } from '@/contexts/auth-context';
import { getAuthErrorMessage } from '@/lib/firebase-errors';
import { fmtIst, loadMyResults, resultUrl, type MockResult, type ResultDownload } from '@/lib/mock-tests';

/**
 * My Results: the student's published mock-test results (score, rank, percentile, pass/fail).
 * Each opens the portal's result page (answers and solutions) or a PDF: scorecard,
 * performance report, answer key and certificates are generated by the portal.
 */
export default function MyResultsScreen() {
  const { firebaseUser } = useAuth();
  const [results, setResults] = useState<MockResult[] | null>(null);
  const [error, setError] = useState('');
  const [refreshing, setRefreshing] = useState(false);

  const load = useCallback(async () => {
    if (!firebaseUser) return;
    setError('');
    try {
      setResults(await loadMyResults(firebaseUser.uid));
    } catch (err) {
      setError(getAuthErrorMessage(err));
      setResults([]);
    }
  }, [firebaseUser]);

  useEffect(() => {
    load();
  }, [load]);

  const open = (examId: string, download?: ResultDownload) => {
    const url = resultUrl(examId, download);
    Linking.openURL(url).catch(() => Alert.alert('Could not open the browser', url));
  };

  return (
    <SafeAreaView style={styles.safe}>
      <ScrollView
        contentContainerStyle={styles.content}
        refreshControl={
          <RefreshControl
            refreshing={refreshing}
            onRefresh={async () => {
              setRefreshing(true);
              await load();
              setRefreshing(false);
            }}
          />
        }
      >
        <Pressable onPress={() => router.back()} accessibilityRole="button">
          <Text style={styles.back}>← Back</Text>
        </Pressable>
        <Text style={styles.title}>My Results</Text>
        <Text style={styles.subtitle}>Published mock-test results. PDFs open on the portal (sign in with this account).</Text>

        {error ? <Text style={styles.error}>{error}</Text> : null}
        {results === null && <ActivityIndicator style={{ marginTop: 30 }} size="large" />}
        {results && results.length === 0 && (
          <View style={[styles.card, { marginTop: 18 }]}>
            <Text style={styles.cardTitle}>No results yet</Text>
            <Text style={styles.muted}>Results appear here after the admin publishes them. Pull down to refresh.</Text>
          </View>
        )}

        {results?.map((r) => (
          <View key={r.examId} style={[styles.card, { marginTop: 14 }]}>
            <Text style={styles.cardTitle}>{r.examTitle}</Text>
            <Text style={styles.mutedSmall}>Submitted {fmtIst(r.submittedAt)}</Text>
            <View style={styles.statRow}>
              <Stat label="Marks" value={`${r.total} / ${r.maxMarks}`} />
              <Stat label="Rank" value={r.rank ? `${r.rank} / ${r.candidates ?? '—'}` : '—'} />
              <Stat label="Percentile" value={r.percentile != null ? r.percentile.toFixed(1) : '—'} />
            </View>
            <Text style={[styles.resultLine, r.pass ? styles.pass : styles.fail]}>
              {r.pass ? 'Pass' : 'Fail'} · {r.percent.toFixed(1)}%
            </Text>
            <Pressable style={styles.primaryBtn} onPress={() => open(r.examId)} accessibilityRole="button">
              <Text style={styles.primaryBtnText}>{'Answers & solutions'}</Text>
            </Pressable>
            <View style={styles.btnRow}>
              <Small label="Scorecard" onPress={() => open(r.examId, 'scorecard')} />
              <Small label="Performance report" onPress={() => open(r.examId, 'report')} />
              <Small label="Answer key PDF" onPress={() => open(r.examId, 'answers')} />
              {r.hasParticipationCert && <Small label="Certificate" onPress={() => open(r.examId, 'certificate')} />}
              {r.hasRankCert && <Small label="Rank certificate" onPress={() => open(r.examId, 'rank')} />}
            </View>
          </View>
        ))}
      </ScrollView>
    </SafeAreaView>
  );
}

function Stat({ label, value }: { label: string; value: string }) {
  return (
    <View style={styles.stat}>
      <Text style={styles.statLabel}>{label}</Text>
      <Text style={styles.statValue}>{value}</Text>
    </View>
  );
}

function Small({ label, onPress }: { label: string; onPress: () => void }) {
  return (
    <Pressable style={styles.ghostBtn} onPress={onPress} accessibilityRole="button">
      <Text style={styles.ghostBtnText}>{label}</Text>
    </Pressable>
  );
}

const styles = StyleSheet.create({
  safe: { flex: 1, backgroundColor: '#F5F8FC' },
  content: { padding: 22, paddingBottom: 40 },
  back: { color: '#2563EB', fontSize: 15, fontWeight: '600', marginTop: 12 },
  title: { fontSize: 28, fontWeight: '700', color: '#111827', marginTop: 12 },
  subtitle: { fontSize: 15, color: '#6B7280', marginTop: 6 },
  card: { backgroundColor: '#FFFFFF', borderRadius: 16, padding: 18, elevation: 2, gap: 6 },
  cardTitle: { fontSize: 17, fontWeight: '700', color: '#111827' },
  muted: { fontSize: 14, color: '#6B7280', lineHeight: 20 },
  mutedSmall: { fontSize: 12, color: '#6B7280' },
  error: { color: '#DC2626', marginTop: 14, fontSize: 14 },
  statRow: { flexDirection: 'row', gap: 10, marginTop: 6 },
  stat: { flex: 1, backgroundColor: '#F3F6FB', borderRadius: 12, padding: 10 },
  statLabel: { fontSize: 12, color: '#6B7280' },
  statValue: { fontSize: 16, fontWeight: '700', color: '#111827', marginTop: 2 },
  resultLine: { fontSize: 15, fontWeight: '700', marginTop: 4 },
  pass: { color: '#15803D' },
  fail: { color: '#DC2626' },
  primaryBtn: { backgroundColor: '#2563EB', borderRadius: 12, paddingVertical: 12, paddingHorizontal: 16, alignItems: 'center', marginTop: 8 },
  primaryBtnText: { color: '#FFFFFF', fontWeight: '700', fontSize: 15 },
  btnRow: { flexDirection: 'row', gap: 8, flexWrap: 'wrap' },
  ghostBtn: { borderColor: '#2563EB', borderWidth: 1, borderRadius: 10, paddingVertical: 8, paddingHorizontal: 12, alignItems: 'center', marginTop: 8 },
  ghostBtnText: { color: '#2563EB', fontWeight: '600', fontSize: 13 },
});
